create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create or replace function public.is_alfa_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_alfa_admin() from public;
grant execute on function public.is_alfa_admin() to anon, authenticated;

drop policy if exists "Admins can read their own admin record" on public.admin_users;
create policy "Admins can read their own admin record"
  on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()));
grant select on public.admin_users to authenticated;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique,
  emoji text not null default '🏋️',
  price numeric(12, 2) not null check (price >= 0),
  name_ru text not null,
  description_ru text not null,
  name_ky text not null,
  description_ky text not null,
  image_path text,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
drop policy if exists "Anyone can read products" on public.products;
create policy "Anyone can read products"
  on public.products for select to anon, authenticated using (true);
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
  on public.products for insert to authenticated with check ((select public.is_alfa_admin()));
drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
  on public.products for update to authenticated
  using ((select public.is_alfa_admin()))
  with check ((select public.is_alfa_admin()));
drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
  on public.products for delete to authenticated using ((select public.is_alfa_admin()));
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

